package com.wangzan101.mika.core.uistate

/**
 * アクションの効果を判定するためのすべてのしきい値が 1 か所に集められています。これらはすべて事前に設定された初期値であり、実機に記録された操作 (操作の前後のインターフェイスと結果) に応じて調整する必要があります。
 * を変更する場合は、ActionEffectTest と FrameDiffTest の例を参照してください。座標は 0 ～ 999 に正規化されます。
 */
object EffectTuning {
    // ---- インターフェース構造 ----
    /** は明らかに変更されました。少なくともこれらの多くの変更は... */
    const val MAJOR_MIN = 3
    /** ...そして少なくともこの割合の要素を占めます。 */
    const val MAJOR_SHARE = 0.10
    /** 同じ入力ボックスの単語が変更されました。前中心と後中心の間の距離はこれを超えてはなりません。 */
    const val NEAR = 50
    /** は、読み返すときに入力ボックスを認識します。中心はこれ以上離れていません。 */
    const val SAME_FIELD = 120
    /** 情報コンテンツ (自己描画インターフェイス) を含む要素がこれよりも少ない場合、画面の広い領域の変更は明らかな変更と見なすことができます。 */
    const val FEW_ELEMENTS = 3

    // ---- 画像 (状況証拠。グリッドとしきい値については FrameTuning を参照) ----
    /** 座標動作は着地点周囲のエリア（半幅）の大きさに依存します。 */
    const val POINT_REGION = 60

    // ---- お待ちください ----
    /** ポートが動作中にインターフェイスを待機しない場合、効果が現れるまでのインターフェイスの安定性の上限が決まります。 */
    const val SETTLE_MS = 1_500L
    /** 同じようであれば、しばらく待ってからもう一度見てください (インターフェイスは非同期で更新される可能性があります)。 */
    const val RECHECK_MS = 700L
    /** アクションを起こす前に確認するのに最も時間がかかります。手遅れの場合は、港の事実に基づいて判断してください。 */
    const val PROBE_MS = 1_000L
    /** アクション後の効果を判断するのにかかる最大時間 (追加の読み取りインターフェイスを待機する)。それが到着したら、既存の事実に基づいて結論を導き出します。 */
    const val BUDGET_MS = 2_500L
}
